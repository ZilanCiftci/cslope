// Writes the engine's JSON schemas (crates/cslope-engine/src/types/schema.rs,
// issue #55) and the Python TypedDicts generated from them:
//
//   bun packages/engine-rs/tools/schema.ts           write
//   bun packages/engine-rs/tools/schema.ts --check   fail when either is stale (CI)
//
// - packages/engine/schema/<name>.json: one file per schema (SCHEMA_NAMES),
//   from `cargo run --release -p cslope-engine --example schemas`.
// - crates/cslope-py/python/cslope/__init__.pyi: the TypedDicts of the
//   shapes in the schemas, between the GENERATED markers; the rest of the
//   stub is written by hand.
//
// Needs the toolchain of rust-toolchain.toml.
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { ENGINE_RS } from "./wasm-source-hash";

const REPO = resolve(ENGINE_RS, "../..");
const SCHEMA_DIR = join(REPO, "packages/engine/schema");
const PYI = join(ENGINE_RS, "crates/cslope-py/python/cslope/__init__.pyi");
const BEGIN = "# ── BEGIN GENERATED by packages/engine-rs/tools/schema.ts from the JSON schemas: do not edit ──";
const END = "# ── END GENERATED ──";

type Json = null | boolean | number | string | Json[] | { [k: string]: Json };
type Schema = { [k: string]: Json };

function cargoSchemas(): Record<string, Schema> {
  const r = spawnSync("cargo", ["run", "-q", "--release", "-p", "cslope-engine", "--example", "schemas"], {
    cwd: ENGINE_RS,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    stdio: ["ignore", "pipe", "inherit"],
  });
  if (r.error) throw new Error(`cargo: ${r.error.message}`);
  if (r.status !== 0) throw new Error(`cargo run --example schemas failed (exit ${r.status})`);
  return JSON.parse(r.stdout) as Record<string, Schema>;
}

const pretty = (v: Json): string => JSON.stringify(v, null, 2) + "\n";

// ── TypedDicts ─────────────────────────────────────────────────────

/** Python names of the Rust types where they differ. */
const RENAME: Record<string, string> = {
  AnalysisOptionsPatch: "AnalysisOptions",
  Issue: "ValidationIssue",
  IntersliceDataPoints: "IntersliceDataPoints",
};

const PY_KEYWORDS = new Set(["from", "class", "def", "import", "global", "lambda", "in", "is", "not", "and", "or", "pass", "return", "None", "True", "False"]);

class Gen {
  /** name -> Python source of the class or alias */
  out = new Map<string, string>();
  /** the definitions of every schema, by name */
  defs = new Map<string, Schema>();
  /** The root being generated: `$ref: "#"` names it. */
  currentRoot = "";

  name(raw: string): string {
    return RENAME[raw] ?? raw;
  }

  ref(s: Schema): string | null {
    const r = s["$ref"];
    if (typeof r !== "string") return null;
    if (r === "#") return this.currentRoot;
    return r.replace(/^#\/\$defs\//, "");
  }

  /** The Python type of a schema; `hint` names an inline object. */
  type(s: Json, hint: string): string {
    if (s === true || s === null || typeof s !== "object" || Array.isArray(s)) return "Any";
    const sc = s as Schema;
    const r = this.ref(sc);
    if (r) {
      this.def(r);
      return this.name(r);
    }
    if ("const" in sc) return `Literal[${JSON.stringify(sc.const)}]`;
    if (Array.isArray(sc.enum)) return `Literal[${sc.enum.map((e) => JSON.stringify(e)).join(", ")}]`;
    const union = (sc.oneOf ?? sc.anyOf) as Json[] | undefined;
    if (Array.isArray(union)) {
      const parts = union.map((b, i) => {
        const bs = b as Schema;
        const title = typeof bs?.title === "string" ? bs.title : `${hint}${i + 1}`;
        return this.type(b, title);
      });
      return unionOf(parts);
    }
    const t = sc.type;
    const types = Array.isArray(t) ? (t as string[]) : typeof t === "string" ? [t] : [];
    if (types.length > 1) return unionOf(types.map((one) => this.type({ ...sc, type: one }, hint)));
    switch (types[0]) {
      case "null":
        return "None";
      case "boolean":
        return "bool";
      case "integer":
        return "int";
      case "number":
        return "float";
      case "string":
        return "str";
      case "array": {
        const items = sc.items as Json;
        if (Array.isArray(sc.prefixItems)) {
          return `Tuple[${(sc.prefixItems as Json[]).map((x) => this.type(x, hint)).join(", ")}]`;
        }
        const n = sc.minItems;
        if (typeof n === "number" && n === sc.maxItems && n > 0 && n <= 4) {
          const one = this.type(items, hint);
          return `Tuple[${Array(n).fill(one).join(", ")}]`;
        }
        return `List[${this.type(items ?? true, hint)}]`;
      }
      case "object": {
        if (sc.properties) {
          this.klass(hint, sc);
          return hint;
        }
        const ap = sc.additionalProperties;
        return `Dict[str, ${ap && ap !== true ? this.type(ap, hint + "Value") : "Any"}]`;
      }
    }
    return "Any";
  }

  def(raw: string): void {
    const name = this.name(raw);
    if (this.out.has(name)) return;
    const s = this.defs.get(raw);
    if (!s) throw new Error(`no definition ${raw}`);
    this.out.set(name, ""); // (a recursive reference)
    if (s.properties) {
      this.klass(name, s);
      return;
    }
    this.out.set(name, `${name} = ${this.type(s, name)}\n`);
  }

  klass(name: string, s: Schema): void {
    if (this.out.get(name)) return;
    this.out.set(name, "");
    const props = s.properties as Record<string, Schema>;
    const required = new Set((s.required as string[] | undefined) ?? []);
    const lines: string[] = [];
    for (const [k, p] of Object.entries(props)) {
      if (PY_KEYWORDS.has(k) || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(k)) {
        throw new Error(`${name}.${k} is not a Python identifier: give the TypedDict a functional form`);
      }
      const t = this.type(p, name + k[0].toUpperCase() + k.slice(1));
      const deprecated = p.deprecated === true ? "  # deprecated" : "";
      lines.push(`    ${k}: ${required.has(k) ? t : `NotRequired[${t}]`}${deprecated}`);
    }
    const doc = typeof s.description === "string" ? docLine(s.description) : "";
    const body = [doc ? `    """${doc}"""\n` : "", ...lines.map((l) => l + "\n")].join("");
    this.out.set(name, `class ${name}(TypedDict):\n${body || "    pass\n"}`);
  }
}

function unionOf(parts: string[]): string {
  const literal = /^Literal\[(.*)\]$/;
  if (parts.length > 1 && parts.every((p) => literal.test(p))) {
    return `Literal[${parts.map((p) => literal.exec(p)![1]).join(", ")}]`;
  }
  const uniq = [...new Set(parts)];
  const hasNone = uniq.includes("None");
  const rest = uniq.filter((p) => p !== "None");
  const inner = rest.length === 1 ? rest[0] : `Union[${rest.join(", ")}]`;
  if (rest.length === 0) return "None";
  return hasNone ? `Optional[${inner}]` : inner;
}

/** The first sentence of a description, for a docstring. */
function docLine(d: string): string {
  const first = d.split(/\n\s*\n/)[0].replace(/\s+/g, " ").trim();
  const sentence = /^(.*?[.!?])(\s|$)/.exec(first)?.[1] ?? first;
  return sentence.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"');
}

/** The schemas whose shapes become TypedDicts, and the name of each root. */
const ROOTS: [string, string][] = [
  ["slope-definition", "SlopeDefinition"],
  ["analysis-options", "AnalysisOptionsPatch"],
  ["analysis-document", "AnalysisDocument"],
  ["analysis-result", "AnalysisResult"],
  ["material-model", "MaterialModel"],
  ["fem-analysis-settings", "FemAnalysisSettings"],
  ["reliability-options", "ReliabilityOptions"],
  ["result-summary", "ResultSummary"],
];

function typedDicts(schemas: Record<string, Schema>): string {
  const g = new Gen();
  const sources = new Map<string, string>();
  for (const [file, s] of Object.entries(schemas)) {
    for (const [k, v] of Object.entries((s["$defs"] ?? {}) as Record<string, Schema>)) {
      const text = JSON.stringify(v);
      const seen = sources.get(k);
      if (seen !== undefined && seen !== text) throw new Error(`$defs/${k} differs between schemas (${file})`);
      sources.set(k, text);
      g.defs.set(k, v);
    }
  }
  for (const [file, root] of ROOTS) {
    const s = { ...schemas[file] };
    for (const k of ["$schema", "$id", "$defs", "x-cslope-schema-version", "title"]) delete s[k];
    g.defs.set(root, s);
    g.currentRoot = root;
    g.def(root);
  }
  // the item of a list schema
  const issues = schemas["validation-issues"];
  g.def(g.ref(issues.items as Schema) ?? "Issue");
  const variables = schemas["random-variables"];
  g.def(g.ref(variables.items as Schema) ?? "RandomVariable");
  const names = [...g.out.keys()].sort();
  return names.map((n) => g.out.get(n)).join("\n");
}

// ── main ───────────────────────────────────────────────────────────

const check = process.argv.includes("--check");
const schemas = cargoSchemas();
const stale: string[] = [];

/** A schema without its descriptions (the properties keep their names): what the engine carries. */
function withoutDescriptions(v: Json, inProperties = false): Json {
  if (Array.isArray(v)) return v.map((x) => withoutDescriptions(x));
  if (v === null || typeof v !== "object") return v;
  const out: { [k: string]: Json } = {};
  for (const [k, x] of Object.entries(v)) {
    if (!inProperties && k === "description") continue;
    out[k] = withoutDescriptions(x, !inProperties && k === "properties");
  }
  return out;
}

const files = new Map<string, string>();
for (const [name, s] of Object.entries(schemas)) files.set(join(SCHEMA_DIR, `${name}.json`), pretty(s as Json));
// The copy the engine builds in (types/schema.rs, `document_schema`): one line, no descriptions.
const EMBEDDED = join(ENGINE_RS, "crates/cslope-engine/src/types/analysis-document.min.json");
files.set(EMBEDDED, JSON.stringify(withoutDescriptions(schemas["analysis-document"] as Json)) + "\n");
if (check) {
  for (const [path, text] of files) {
    if (!existsSync(path) || readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== text) stale.push(path);
  }
  if (existsSync(SCHEMA_DIR)) {
    for (const f of readdirSync(SCHEMA_DIR)) {
      if (f.endsWith(".json") && !files.has(join(SCHEMA_DIR, f))) stale.push(join(SCHEMA_DIR, f) + " (no such schema)");
    }
  }
} else {
  mkdirSync(SCHEMA_DIR, { recursive: true });
  // (the engine needs its copy to build before it can generate the schemas)
  for (const [path, text] of files) writeFileSync(path, text);
}

const pyi = readFileSync(PYI, "utf8").replace(/\r\n/g, "\n");
const a = pyi.indexOf(BEGIN);
const b = pyi.indexOf(END);
if (a < 0 || b < a) throw new Error(`${PYI} has no ${BEGIN} … ${END} block`);
const generated = `${BEGIN}\n# Schema version ${String((schemas["slope-definition"] as Schema)["x-cslope-schema-version"])}.\n\n${typedDicts(schemas)}\n`;
const next = pyi.slice(0, a) + generated + pyi.slice(b);
if (check) {
  if (next !== pyi) stale.push(PYI);
} else {
  writeFileSync(PYI, next);
}

if (stale.length > 0) {
  console.error(`Stale (run \`bun packages/engine-rs/tools/schema.ts\` and commit):\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
console.log(check ? `The schemas and the TypedDicts are fresh (${Object.keys(schemas).length} schemas).` : `Wrote ${Object.keys(schemas).length} schemas, the engine's copy and the TypedDicts.`);
